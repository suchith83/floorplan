"""Evaluation on your own home: plans vs tape measurements, repeatability between two video runs,
and video vs photos. Reads data/home/measurements.yaml (template: eval/measurements.template.yaml).

Room names: photo runs name rooms after their folders. For video runs, look at out/<run>/plan.svg once
and add which plan room is which to measurements.yaml:
    plan_rooms:
      video_1: {R1: kitchen, R2: bedroom1}
      video_2: {R2: kitchen, R1: bedroom1}
Usage: uv run python eval/run_home.py [--runs video_1,video_2,photos]   (run `fp run` on each first)
Writes eval/results_home.md."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import yaml

HOME = Path("data/home")


def room_sides(room: dict) -> dict:
    """width (short side) and length (long side) of a plan room, each with whether both walls were seen
    and the confidence of the walls whose length it is."""
    out = []
    for name in ("x", "y"):
        bound = [w for w in room["walls"] if w["axis"] == name]
        lo, hi = min(bound, key=lambda w: w["coord"]), max(bound, key=lambda w: w["coord"])
        along = [w["confidence"] for w in room["walls"] if w["axis"] != name]
        out.append({"m": round(hi["coord"] - lo["coord"], 3), "observed": lo["observed"] and hi["observed"],
                    "confidence": max(along) if along else None})
    out.sort(key=lambda s: s["m"])
    return {"width": out[0], "length": out[1]}


def main(runs: list[str]):
    meas = yaml.safe_load((HOME / "measurements.yaml").read_text())
    mapping = meas.get("plan_rooms", {})
    rows, by_room = [], {}
    for run in runs:
        plan_path = Path("out") / run / "plan.json"
        if not plan_path.exists():
            print(f"skip {run}: run `uv run fp run` on it first")
            continue
        plan = json.loads(plan_path.read_text())
        names = mapping.get(run, {})
        for r in plan["rooms"]:
            name = names.get(r["id"], r["name"])
            tape = meas.get("rooms", {}).get(name)
            sides = room_sides(r)
            for dim in ("width", "length"):
                ours = sides[dim]
                truth = np.mean(tape[dim]) if tape and tape.get(dim) else None
                err = None if truth is None else round(100 * (ours["m"] - truth), 1)
                rows.append({"run": run, "input": plan["source"]["input"], "room": name, "dim": dim, "ours_m": ours["m"],
                             "tape_m": None if truth is None else round(float(truth), 3), "err_cm": err,
                             "observed": ours["observed"], "confidence": ours["confidence"]})
                by_room.setdefault((name, dim), {})[run] = ours["m"]
    lines = ["# Results on the home capture", "", "Generated by `eval/run_home.py` from data/home/measurements.yaml.", "",
             "| Run | Input | Room | Side | Ours (m) | Tape (m) | Error (cm) | Both walls seen | Confidence |",
             "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in rows:
        lines.append(f"| {r['run']} | {r['input']} | {r['room']} | {r['dim']} | {r['ours_m']:.3f} | "
                     f"{r['tape_m'] if r['tape_m'] is not None else '—'} | {r['err_cm'] if r['err_cm'] is not None else '—'} | "
                     f"{'yes' if r['observed'] else 'no'} | {r['confidence']} |")
    errs = [abs(r["err_cm"]) for r in rows if r["err_cm"] is not None and r["observed"]]
    if errs:
        lines += ["", f"Against tape, sides with both walls seen: MAE {np.mean(errs):.1f} cm, max {max(errs):.1f} cm, n = {len(errs)}."]
    vids = [r for r in runs if r.startswith("video")]
    sds = [100 * np.std([v[k] for k in vids], ddof=1) for v in by_room.values() if all(k in v for k in vids)]
    if len(vids) > 1 and sds:
        lines.append(f"Repeatability, {' vs '.join(vids)}: median SD {np.median(sds):.1f} cm over {len(sds)} room sides.")
    out = Path(__file__).parent / "results_home.md"
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default="video_1,video_2,photos")
    main(ap.parse_args().runs.split(","))
